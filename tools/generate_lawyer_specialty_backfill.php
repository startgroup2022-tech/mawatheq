<?php
/**
 * Generate MAWATHEQ_LAWYER_SPECIALTY_BACKFILL.sql.
 *
 *   php tools/generate_lawyer_specialty_backfill.php [--out=path]
 *
 * Why this exists: `api/v1/journey.php` decides which lawyers appear under a legal
 * specialty. A server whose `includes/legal_journey.php` predates commit d1de2ca
 * computes that only from explicit `lawyer_specialties` rows — it never falls back to
 * the lawyer's own declared `specialization`. A real, approved lawyer who declared
 * `قانون جنائي` but has no link row is therefore invisible in the journey, and the
 * customer is told no lawyer exists.
 *
 * The code fix is to deploy the current `includes/legal_journey.php`. This file is the
 * data-only alternative for an owner who cannot deploy code: it writes the missing
 * `lawyer_specialties` rows so the OLD code finds the lawyer too. Both paths converge
 * on the same visible result, and the new code treats an explicit link as
 * authoritative — so running this first is harmless once the code is deployed.
 *
 * The emitted SQL is **self-contained**: it resolves the lawyer→category link on the
 * server it runs against, from that server's own `lawyers` and `najiz_categories`
 * rows. No id from the generating machine is embedded, so the file is correct on any
 * deployment regardless of its auto-increment values.
 *
 * The mapping is `legal_journey_specialization_categories()` — the same array the
 * runtime uses — so the file can never disagree with the code about which specialty a
 * declared value belongs to. Re-run the generator whenever that map changes.
 *
 * Output rules, because this runs against production:
 *   - `INSERT IGNORE` only. The unique key is (lawyer_id, category_id), so a second run
 *     inserts nothing; a link an operator created by hand is never overwritten.
 *   - Only `status = 'approved'` lawyers, matching what the endpoints list.
 *   - Only categories that exist and are `is_active = 1`, matching the runtime index.
 *   - No UPDATE, no DELETE, no DDL, no table creation.
 */

require_once __DIR__ . '/../config/config.php';
require_once __DIR__ . '/../includes/legal_journey.php';

$out = dirname(__DIR__) . '/database/MAWATHEQ_LAWYER_SPECIALTY_BACKFILL.sql';
foreach ($argv as $arg) {
    if (str_starts_with($arg, '--out=')) $out = substr($arg, 6);
}

/** Escape for a MySQL single-quoted literal. */
function sql_str(string $v): string {
    return "'" . str_replace(
        ["\\", "\0", "\n", "\r", "\x1a", "'"],
        ["\\\\", "\\0", "\\n", "\\r", "\\Z", "\\'"],
        $v
    ) . "'";
}

$map = legal_journey_specialization_categories();

// Every (declared specialization, category name) pair the runtime would honour.
$pairs = [];
foreach ($map as $spec => $catNames) {
    foreach ($catNames as $catName) {
        $pairs[] = [$spec, $catName];
    }
}

// Reference counts, from the database the generator ran against. They describe this
// machine, not the target; the target reports its own numbers in the verify section.
$catIdByName = [];
foreach ($pdo->query("SELECT id, name_ar FROM najiz_categories WHERE is_active = 1")->fetchAll() as $r) {
    $catIdByName[trim((string)$r['name_ar'])] = (int)$r['id'];
}
$approved = $pdo->query("SELECT specialization FROM lawyers WHERE status = 'approved'")->fetchAll();
$mapped = 0;
$unmapped = [];
foreach ($approved as $lw) {
    $spec = trim((string)$lw['specialization']);
    $hit = false;
    foreach ($map[$spec] ?? [] as $catName) {
        if (isset($catIdByName[$catName])) { $hit = true; break; }
    }
    if ($hit) { $mapped++; } else { $unmapped[$spec] = ($unmapped[$spec] ?? 0) + 1; }
}

$now = date('Y-m-d');
$b = [];
$b[] = '-- MAWATHEQ — lawyer specialty backfill (data-only)';
$b[] = '--';
$b[] = '-- Generated by tools/generate_lawyer_specialty_backfill.php on ' . $now . '.';
$b[] = '--';
$b[] = '-- PURPOSE';
$b[] = '--   Make approved lawyers visible in the consultation journey on a server whose';
$b[] = '--   includes/legal_journey.php predates the declared-specialization fallback.';
$b[] = '--   It writes the missing lawyer_specialties rows, so both the old and the new';
$b[] = '--   code find the lawyer. The new code treats an explicit link as authoritative,';
$b[] = '--   so running this before the code deploy changes nothing once the code lands.';
$b[] = '--';
$b[] = '-- HOW IT WORKS';
$b[] = '--   One INSERT ... SELECT. It matches each approved lawyer\'s own declared';
$b[] = '--   specialization to a live category through the same map the runtime uses,';
$b[] = '--   and inserts the link. It reads the target server\'s own rows, so no id from';
$b[] = '--   another machine is embedded and the file is correct on any deployment.';
$b[] = '--';
$b[] = '-- SAFETY';
$b[] = '--   * INSERT IGNORE only. Unique key (lawyer_id, category_id): a second run adds';
$b[] = '--     nothing, and a link an operator made by hand is never overwritten.';
$b[] = '--   * No UPDATE, no DELETE, no DDL, no table creation.';
$b[] = '--   * Only approved lawyers and live categories, matching the runtime.';
$b[] = '--   * No client, case, document or payment data is read or written.';
$b[] = '--';
$b[] = '-- PREREQUISITE';
$b[] = '--   The najiz_* tables and lawyer_specialties must exist (see';
$b[] = '--   MAWATHEQ_DB_SCHEMA_FIX.sql). This file does not create them.';
$b[] = '--';
$b[] = '-- REFERENCE COUNTS (from the generator\'s own database, for orientation only)';
$b[] = '--   approved lawyers with a mappable specialization: ' . $mapped;
$b[] = '--   approved lawyers with no mappable specialization: ' . count($unmapped) . ' distinct value(s)';
foreach ($unmapped as $spec => $n) {
    $b[] = '--     ' . ($spec === '' ? '(empty)' : $spec) . '  x' . $n;
}
$b[] = '--   The target reports its own numbers in the VERIFY section below.';
$b[] = '--';
$b[] = '-- VERIFY AFTER RUNNING (run each SELECT on the target)';
$b[] = '--   -- 1. how many links exist now';
$b[] = '--   SELECT COUNT(*) AS links FROM lawyer_specialties;';
$b[] = '--';
$b[] = '--   -- 2. approved lawyers that are now discoverable, and under which specialty';
$b[] = '--   SELECT l.id, l.full_name, c.name_ar AS specialty';
$b[] = '--     FROM lawyer_specialties ls';
$b[] = '--     JOIN lawyers l ON l.id = ls.lawyer_id';
$b[] = '--     JOIN najiz_categories c ON c.id = ls.category_id';
$b[] = '--    WHERE l.status = \'approved\'';
$b[] = '--    ORDER BY l.id;';
$b[] = '--';
$b[] = '--   -- 3. approved lawyers still not linked to anything';
$b[] = '--   SELECT l.id, l.full_name, l.specialization';
$b[] = '--     FROM lawyers l';
$b[] = '--    WHERE l.status = \'approved\'';
$b[] = '--      AND NOT EXISTS (SELECT 1 FROM lawyer_specialties ls WHERE ls.lawyer_id = l.id);';
$b[] = '--';
$b[] = '--   Then confirm from the app:';
$b[] = '--     GET /api/v1/journey.php?action=specialties   -> lawyer_count >= 1 for a staffed one';
$b[] = '--     GET /api/v1/journey.php?action=lawyers&category_id=<id>  -> matched:true';
$b[] = '--';
$b[] = 'SET NAMES utf8mb4;';
$b[] = '';
$b[] = 'INSERT IGNORE INTO lawyer_specialties (lawyer_id, category_id)';
$b[] = 'SELECT l.id, c.id';
$b[] = '  FROM lawyers l';
$b[] = '  JOIN (';
$first = true;
foreach ($pairs as [$spec, $catName]) {
    $b[] = ($first ? '         SELECT ' : '  UNION ALL SELECT ')
        . sql_str($spec) . ' AS spec, ' . sql_str($catName) . ' AS cat';
    $first = false;
}
$b[] = '       ) m ON m.spec = TRIM(l.specialization)';
$b[] = '  JOIN najiz_categories c ON c.name_ar = m.cat AND c.is_active = 1';
$b[] = ' WHERE l.status = \'approved\';';
$b[] = '';

$sql = implode("\n", $b);
if (file_put_contents($out, $sql) === false) {
    fwrite(STDERR, "cannot write $out\n");
    exit(1);
}

printf("wrote %s\n", $out);
printf("  mapping pairs                 : %d\n", count($pairs));
printf("  reference: approved mapped    : %d\n", $mapped);
printf("  reference: approved unmapped  : %d\n", count($unmapped));
